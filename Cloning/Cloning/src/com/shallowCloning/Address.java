package com.shallowCloning;

public class Address {
	String line1;
	String line2;
	String city;
	/**
	 * @param line1
	 * @param line2
	 * @param city
	 */
	public Address(String line1, String line2, String city) {
		super();
		this.line1 = line1;
		this.line2 = line2;
		this.city = city;
	}
	

}
